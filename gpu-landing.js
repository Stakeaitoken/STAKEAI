const languageButtons = document.querySelectorAll('[data-language]');

function setLandingLanguage(language) {
    const copy = landingCopy[language];
    if (!copy) throw new Error(`Unsupported landing page language: ${language}`);

    document.documentElement.lang = language;
    document.title = copy.title;
    document.querySelector('meta[name="description"]').setAttribute('content', copy.description);
    document.querySelector('meta[property="og:title"]').setAttribute('content', copy.title);
    document.querySelector('meta[property="og:description"]').setAttribute('content', copy.description);
    document.querySelector('meta[name="twitter:title"]').setAttribute('content', copy.title);
    document.querySelector('meta[name="twitter:description"]').setAttribute('content', copy.description);

    document.querySelectorAll('[data-copy]').forEach((element) => {
        const key = element.dataset.copy;
        if (!Object.hasOwn(copy, key)) throw new Error(`Missing ${language} landing translation: ${key}`);
        element.textContent = copy[key];
    });
    languageButtons.forEach((button) => {
        const isSelected = button.dataset.language === language;
        button.setAttribute('aria-pressed', String(isSelected));
        button.classList.toggle('text-white', isSelected);
        button.classList.toggle('text-gray-400', !isSelected);
    });
}

languageButtons.forEach((button) => {
    button.addEventListener('click', () => setLandingLanguage(button.dataset.language));
});
